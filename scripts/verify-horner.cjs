const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const baseUrl = process.env.READER_BASE_URL || 'http://127.0.0.1:4174';
const out = 'docs/verification/phase2-horner';
let browser;
(async () => {
  browser = await chromium.launch({ executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', headless: true });
  const checks = [];
  for (const width of [1440, 390]) for (const lang of ['zh', 'en']) {
    const context = await browser.newContext({ viewport: { width, height: 1000 }, locale: lang === 'zh' ? 'zh-CN' : 'en-US' });
    const page = await context.newPage(); const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const go = async route => { assert.equal((await page.goto(baseUrl + route)).status(), 200); await page.locator('h1').waitFor(); };
    await go('/book/8#section-8-1');
    await page.locator('#section-8-1 a[href*="/horner"]').click(); await page.locator('h1').waitFor();
    await page.reload(); await page.locator('h1').waitFor(); assert.equal(new URL(page.url()).pathname, '/horner');
    await page.goBack(); await page.locator('#section-8-1').waitFor();
    await page.goForward(); await page.locator('h1').waitFor();
    const h = page.getByTestId('polynomial-horner'), d = page.getByTestId('polynomial-direct');
    await h.getByRole('slider').fill('3');
    const state = await h.getByTestId('variables').innerText();
    await page.getByRole('button', { name: lang === 'zh' ? 'English' : '中文', exact: true }).click();
    assert.equal(await h.getByTestId('variables').innerText(), state);
    assert.equal(await h.locator('[aria-current="step"]').getAttribute('data-line'), 'multiply');
    await h.getByRole('slider').fill('2');
    assert.match(await h.getByTestId('explanation').innerText(), lang === 'zh' ? /Move to/ : /移到/);
    await h.getByRole('slider').fill('4');
    assert.match(await h.getByTestId('explanation').innerText(), lang === 'zh' ? /Add the/ : /加上/);
    await page.getByRole('button', { name: lang === 'zh' ? '中文' : 'English', exact: true }).click();
    await h.getByRole('button', { name: lang === 'zh' ? '播放' : 'Play', exact: true }).click();
    await page.getByRole('button', { name: '[2,0,4,5]', exact: true }).click();
    await page.waitForTimeout(1200); assert.equal(await h.getByRole('slider').inputValue(), '0');
    for (const p of [h, d]) await p.getByRole('slider').fill(await p.getByRole('slider').getAttribute('max'));
    assert.equal(await h.getByTestId('sum').innerText(), '29'); assert.equal(await d.getByTestId('sum').innerText(), '29');
    await h.getByRole('button', { name: lang === 'zh' ? '上一步' : 'Step Backward', exact: true }).click();
    await h.getByRole('button', { name: lang === 'zh' ? '下一步' : 'Step Forward', exact: true }).click();
    assert.equal(await h.getByTestId('sum').innerText(), '29');
    await page.getByRole('button', { name: '[2,3,4,5]', exact: true }).click();
    for (const p of [h, d]) await p.getByRole('slider').fill(await p.getByRole('slider').getAttribute('max'));
    assert.equal(await h.getByTestId('sum').innerText(), '41');
    assert.match(await h.getByTestId('counts').innerText(), /3.*3/); assert.match(await d.getByTestId('counts').innerText(), /6.*3/);
    const summary = page.locator('summary'); await summary.focus(); await page.keyboard.press('Enter');
    assert.equal(await page.locator('details').getAttribute('open'), '');
    const copy = await page.locator('body').innerText();
    assert.doesNotMatch(copy, /页码|页序|PDF page|第\s*\d+\s*页/);
    if (lang === 'en') assert.doesNotMatch(copy.replaceAll('中文', ''), /[\u3400-\u9fff]/);
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1);
    assert.equal(overflow, false); assert.deepEqual(errors, []);
    await page.screenshot({ path: `${out}/horner-${lang}-${width}.png`, fullPage: true });
    checks.push({ baseUrl, width, lang, passed: ['chapter entry', 'direct route refresh', 'back/forward', 'language preserves state and code highlight', 'replay explanations switch language', 'input during playback resets both players', 'new-input forward/back', '41 and operation counts', 'keyboard disclosure', 'no page numbers', 'no page overflow'], errors });
    await context.close();
  }
  fs.writeFileSync(`${out}/browser-audit.json`, JSON.stringify(checks, null, 2));
  console.log('PASS: Horner production preview, both languages at 1440/390.');
  await browser.close();
})().catch(async e => { console.error(e); await browser?.close(); process.exitCode = 1; });
